// Static build (GitHub Pages preview, or hoster.kz at the domain root with an empty base path): `NEXT_PUBLIC_BASE_PATH=/repo NEXT_PUBLIC_SITE_URL=https://user.github.io/repo npm run build:pages`
// API routes need a server, so they are moved aside for the build and restored afterwards.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, extname, basename } from "node:path";
import sharp from "sharp";
import { DEVICE_SIZES, IMAGE_SIZES } from "../next.config.mjs";

const base = (process.env.NEXT_PUBLIC_BASE_PATH || "").replace(/\/$/, "");
const api = "src/app/api", parked = ".api-parked";
if (existsSync(parked)) throw new Error(`${parked} exists: restore it to ${api} first.`);
renameSync(api, parked);
try {
  execSync("next build", { stdio: "inherit", env: { ...process.env, NEXT_PUBLIC_STATIC_EXPORT: "1" } });
} finally {
  renameSync(parked, api);
}

const redirectPage = (to) =>
  `<!doctype html><meta charset="utf-8"><meta name="robots" content="noindex"><title>Almaty Snowboard</title><link rel="canonical" href="${to}"><meta http-equiv="refresh" content="0; url=${to}"><a href="${to}">${to}</a>`;
writeFileSync("out/index.html", redirectPage(`${base}/ru/`));
for (const r of JSON.parse(readFileSync("content/redirects.json", "utf8"))) {
  const file = join("out", r.source, "index.html");
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, redirectPage(base + r.destination));
}
// Pages that call notFound() (e.g. /team/ without team data) are exported as HTML with status 200 on static hosts.
// Remove them so GitHub Pages serves the real 404.html instead.
const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));
for (const f of walk("out").filter((f) => f.endsWith("index.html"))) {
  if (readFileSync(f, "utf8").includes("NEXT_HTTP_ERROR_FALLBACK;404")) rmSync(dirname(f), { recursive: true });
}
// Pre-render responsive WebP variants for src/lib/img-loader.ts (no image server on Pages).
for (const f of readdirSync("public/images").filter((f) => /\.(jpe?g|png|webp)$/i.test(f))) {
  const name = basename(f, extname(f));
  for (const w of [...IMAGE_SIZES, ...DEVICE_SIZES]) {
    await sharp(join("public/images", f)).resize({ width: w, withoutEnlargement: true }).webp({ quality: 80 }).toFile(join("out/images", `${name}-${w}w.webp`));
  }
}
writeFileSync("out/.nojekyll", "");

// Apache shared hosting (hoster.kz): served from the domain root, so real 301s, https, caching and headers live in .htaccess.
// GitHub Pages ignores this file.
if (!base) {
  const origin = (process.env.NEXT_PUBLIC_SITE_URL || "").replace(/\/$/, "");
  const host = origin.replace(/^https?:\/\//, "");
  const forceHttps = process.env.FORCE_HTTPS !== "0" && origin.startsWith("https://");
  const esc = (p) => p.replace(/^\//, "").replace(/\/$/, "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const lines = [
    "# Generated by scripts/build-pages.mjs. Do not edit on the server: the next deploy overwrites it.",
    "Options -Indexes",
    "DirectoryIndex index.html",
    "ErrorDocument 404 /404.html",
    "AddDefaultCharset utf-8",
    "AddType text/plain .txt",
    "AddType image/avif .avif",
    "AddType image/webp .webp",
    "",
    "<IfModule mod_rewrite.c>",
    "RewriteEngine On",
    "RewriteRule ^\\.well-known/acme-challenge/ - [L]",
    ...(host && forceHttps
      ? [
          "# One address for search engines: https, no www.",
          "RewriteCond %{HTTPS} !=on",
          "RewriteCond %{HTTP:X-Forwarded-Proto} !=https",
          "RewriteCond %{HTTP:X-Forwarded-Ssl} !=on",
          `RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]`,
        ]
      : []),
    ...(host ? ["RewriteCond %{HTTP_HOST} ^www\\. [NC]", `RewriteRule ^ ${forceHttps ? "https" : "http"}://${host}%{REQUEST_URI} [R=301,L]`] : []),
    "# Old page addresses (content/redirects.json, editable in the CMS).",
    ...JSON.parse(readFileSync("content/redirects.json", "utf8")).map((r) => `RewriteRule ^${esc(r.source)}/?$ ${r.destination} [R=301,L]`),
    "# Language root. Temporary, so the default language can change later.",
    "RewriteRule ^$ /ru/ [R=302,L]",
    "</IfModule>",
    "",
    "<IfModule mod_headers.c>",
    'Header always set X-Content-Type-Options "nosniff"',
    'Header always set Referrer-Policy "strict-origin-when-cross-origin"',
    'Header always set X-Frame-Options "SAMEORIGIN"',
    'Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"',
    '<FilesMatch "\\.(html|xml|txt|json)$">',
    'Header set Cache-Control "no-cache"',
    "</FilesMatch>",
    "</IfModule>",
    "",
    "<IfModule mod_expires.c>",
    "ExpiresActive On",
    'ExpiresByType image/webp "access plus 30 days"',
    'ExpiresByType image/jpeg "access plus 30 days"',
    'ExpiresByType image/png "access plus 30 days"',
    'ExpiresByType image/svg+xml "access plus 30 days"',
    'ExpiresByType font/woff2 "access plus 1 year"',
    'ExpiresByType text/css "access plus 1 year"',
    'ExpiresByType application/javascript "access plus 1 year"',
    'ExpiresByType text/javascript "access plus 1 year"',
    "</IfModule>",
    "",
    "<IfModule mod_deflate.c>",
    "AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml application/javascript text/javascript application/json image/svg+xml",
    "</IfModule>",
    "",
  ];
  writeFileSync("out/.htaccess", lines.join("\n"));
}
console.log(`Static site in out/ (base path "${base || "/"}")`);
